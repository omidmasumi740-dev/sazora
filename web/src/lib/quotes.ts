/** جمله روز — بر اساس تاریخ شمسی، قطعی و بدون اینترنت */
export function quoteOfDay(jalaliDate: string): Quote {
  let h = 0
  for (let i = 0; i < jalaliDate.length; i++) {
    h = (h * 31 + jalaliDate.charCodeAt(i)) >>> 0
  }
  return QUOTES[h % QUOTES.length]!
}

/** یک جمله تصادفی (برای دکمه «یکی دیگه») */
export function randomQuote(except?: Quote): Quote {
  const pool = except ? QUOTES.filter((q) => q !== except) : QUOTES
  return pool[Math.floor(Math.random() * pool.length)]!
}
